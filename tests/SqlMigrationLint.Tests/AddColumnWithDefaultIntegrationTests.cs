using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using SqlMigrationLint;
using Xunit;

namespace SqlMigrationLint.Tests;

/// <summary>
/// End-to-end tests for <see cref="AddColumnWithDefaultRule"/>: realistic EF Core migration files are written to disk
/// and pushed through <see cref="MigrationLinter.Lint(string)"/> (file discovery -> parsing -> rules -> report).
/// </summary>
public sealed class AddColumnWithDefaultIntegrationTests : IDisposable
{
    private const string RuleId = "add-column-with-default";

    private readonly string _root = Path.Combine(Path.GetTempPath(), "sqlmigrationlint-it-" + Guid.NewGuid().ToString("N"));

    public AddColumnWithDefaultIntegrationTests()
    {
        Directory.CreateDirectory(Path.Combine(_root, "Migrations"));
    }

    public void Dispose()
    {
        if (Directory.Exists(_root))
        {
            Directory.Delete(_root, recursive: true);
        }
    }

    [Fact]
    public void Lint_NotNullColumnWithDefaultOnExistingTable_ReportsWarningAtStatementLine()
    {
        var path = WriteMigration("20261024100000_AddOrderStatus", new[]
        {
            "ALTER TABLE \"Orders\" ADD COLUMN \"Status\" integer NOT NULL DEFAULT 0;"
        });

        var report = MigrationLinter.CreateDefault().Lint(_root);

        var finding = Assert.Single(report.Findings);
        Assert.Equal(RuleId, finding.RuleName);
        Assert.Equal(LintSeverity.Warning, finding.Severity);
        Assert.Equal(
            "Adding column 'Status' with default value to existing table 'Orders' causes table rewrite. " +
            "Consider using a nullable column without default or add default in a separate migration.",
            finding.Message);
        Assert.Equal(path, finding.File);
        Assert.Equal(ExpectedLineOf(path, "ADD COLUMN \"Status\""), finding.Line);
        Assert.Equal(1, report.MigrationsScanned);
    }

    [Fact]
    public void Lint_NullableColumnWithoutDefault_ReportsNoFindings()
    {
        WriteMigration("20261024100000_AddOrderNotes", new[]
        {
            "ALTER TABLE \"Orders\" ADD COLUMN \"Notes\" text NULL;"
        });

        var report = MigrationLinter.CreateDefault().Lint(_root);

        Assert.DoesNotContain(report.Findings, f => f.RuleName == RuleId);
        Assert.Empty(report.Findings);
        Assert.Equal(1, report.MigrationsScanned);
    }

    [Fact]
    public void Lint_TwoOffendingAddColumnStatements_ReportsTwoFindingsInStatementOrder()
    {
        var path = WriteMigration("20261024100000_AddOrderFlags", new[]
        {
            "ALTER TABLE \"Orders\" ADD COLUMN \"IsArchived\" boolean NOT NULL DEFAULT FALSE;",
            "ALTER TABLE \"Orders\" ADD COLUMN \"Priority\" integer NOT NULL DEFAULT 5;"
        });

        var report = MigrationLinter.CreateDefault().Lint(_root);

        Assert.Equal(2, report.Findings.Count);
        Assert.All(report.Findings, f => Assert.Equal(RuleId, f.RuleName));
        Assert.All(report.Findings, f => Assert.Equal(path, f.File));

        var first = report.Findings[0];
        var second = report.Findings[1];

        Assert.Contains("'IsArchived'", first.Message);
        Assert.Equal(ExpectedLineOf(path, "ADD COLUMN \"IsArchived\""), first.Line);

        Assert.Contains("'Priority'", second.Message);
        Assert.Equal(ExpectedLineOf(path, "ADD COLUMN \"Priority\""), second.Line);

        Assert.True(first.Line < second.Line);
    }

    [Fact]
    public void Lint_UnrelatedCreateTable_ReportsNoFindings()
    {
        WriteMigration("20261024100000_CreateCustomers", new[]
        {
            "CREATE TABLE \"Customers\" (",
            "    \"Id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,",
            "    \"Email\" text NOT NULL,",
            "    \"CreatedAt\" timestamp with time zone NOT NULL DEFAULT now()",
            ");"
        });

        var report = MigrationLinter.CreateDefault().Lint(_root);

        Assert.Empty(report.Findings);
        Assert.Equal(1, report.MigrationsScanned);
    }

    /// <summary>
    /// Writes a realistic EF Core migration whose <c>Up</c> runs the given SQL statements through
    /// <c>migrationBuilder.Sql</c>, and whose <c>Down</c> is non-empty so unrelated rules stay quiet.
    /// </summary>
    private string WriteMigration(string fileName, IEnumerable<string> upStatements)
    {
        var className = fileName.Substring(fileName.IndexOf('_') + 1);
        var sb = new StringBuilder();
        sb.AppendLine("using Microsoft.EntityFrameworkCore.Migrations;");
        sb.AppendLine();
        sb.AppendLine("#nullable disable");
        sb.AppendLine();
        sb.AppendLine("namespace Sarmkadan.Orders.Migrations");
        sb.AppendLine("{");
        sb.AppendLine($"    [DbContext(typeof(OrdersDbContext))]");
        sb.AppendLine($"    [Migration(\"{fileName}\")]");
        sb.AppendLine($"    public partial class {className} : Migration");
        sb.AppendLine("    {");
        sb.AppendLine("        protected override void Up(MigrationBuilder migrationBuilder)");
        sb.AppendLine("        {");
        sb.AppendLine("            migrationBuilder.Sql(@\"");
        foreach (var statement in upStatements)
        {
            sb.AppendLine("                " + statement);
        }
        sb.AppendLine("            \");");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        protected override void Down(MigrationBuilder migrationBuilder)");
        sb.AppendLine("        {");
        sb.AppendLine("            migrationBuilder.Sql(\"ALTER TABLE \\\"Orders\\\" DROP COLUMN IF EXISTS \\\"Placeholder\\\";\");");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        var path = Path.Combine(_root, "Migrations", fileName + ".cs");
        File.WriteAllText(path, sb.ToString());
        return path;
    }

    /// <summary>
    /// Returns the 1-based line number of the first line in <paramref name="path"/> containing <paramref name="marker"/>.
    /// </summary>
    private static int ExpectedLineOf(string path, string marker)
    {
        var lines = File.ReadAllLines(path);
        var index = Array.FindIndex(lines, l => l.Contains(marker, StringComparison.Ordinal));
        Assert.True(index >= 0, $"Marker '{marker}' not found in {path}.");
        return index + 1;
    }
}
